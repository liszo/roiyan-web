const monthFormatter = new Intl.DateTimeFormat("fa-IR-u-ca-persian", {
  month: "long",
  timeZone: "Asia/Tehran",
});

/** {month} in the deck: the current Persian month. Cached and refreshed daily (cacheComponents). */
export async function currentMonth(): Promise<string> {
  "use cache";
  cacheLife("days");
  return monthFormatter.format(new Date());
}

